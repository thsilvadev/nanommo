// Real-shape battle fixtures for the arena specs (Karma can't run the engine).
// Writes solo-v2.fixture.ts and party-v2.fixture.ts. Run after `pnpm --filter @nanommo/shared build`:  node make-fixtures.mjs
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../../../../../../../..');
const require = createRequire(import.meta.url);
const shared = require(path.join(root, 'packages/shared/dist'));
const monsters = require(path.join(root, 'monsters.json'));
const statuses = Object.fromEntries(require(path.join(root, 'status_effects.json')).statusEffects.map((s) => [s.id, s]));
const list = Array.isArray(monsters) ? monsters : (monsters.monsters ?? Object.values(monsters).flat());
const monster = (id) => list.find((m) => m.id === id);

const attack = [{ priority: 1, conditions: [{ id: 'always' }], action: { id: 'attack' } }];
const stats = (extra = {}) => ({
  level: 12, hp: 900, maxHp: 900, sp: 80, maxSp: 80, atk: 70, matk: 10, def: 10, mdefPercent: 0, accuracy: 200, evasion: 5,
  critChance: 10, hpRegenPerTenTicks: 0, spRegenPerTenTicks: 0, agi: 10, dex: 20, attackSpeed: 800, moveSpeed: 100, ...extra,
});
const START = Date.parse('2026-11-24T12:00:00.000Z');
const iso = (ms) => new Date(ms).toISOString();

// Solo: a bow character against a melee monster that walks up to it (move events).
const bee = monster('mon_mutantbee');
const solo = shared.simulateBattleV2Solo(
  stats({ atk: 18, characterId: 'char-self', characterName: 'Archer', basicAttackDamageType: 'ranged', basicAttackRange: 8, combatStyle: 'ranged' }),
  bee, attack, 'arena-fixture-solo', { statusEffectDefs: statuses },
);
const soloEntry = {
  id: 'entry-1', characterId: 'char-self', sequenceIndex: 1, tickDurationMs: 500, mapId: 'map_green_grounds_2',
  monsterId: bee.id, startAt: iso(START), endAt: iso(START + solo.durationTicks * 500), cancelledAt: null, cancellationReason: null,
  outcome: solo.outcome, log: { header: solo.log.header, v2Events: solo.log.v2Events, events: [], outcome: solo.outcome, durationTicks: solo.durationTicks },
};

// Party: two melee characters against three monsters (one principal pair, two raid extras).
const wolf = monster('mon_direwolf'), slime = monster('mon_slime');
const mon = (def, i, principalActorId, role) => ({
  id: `monster:${def.id}:${i}`, kind: 'monster', team: 'b', position: { row: 5, column: 9 }, definitionId: def.id, name: def.name,
  snapshot: { ...shared.BattleEngine.buildMonsterSnapshot(def) }, gambits: def.gambit ?? attack, inventory: {},
  attackIntervalTicks: def.atkSpeedTicks, principalActorId, encounterRole: role, orderIndex: i,
});
const chars = ['char-self', 'char-ally'].map((id, i) => ({
  id, kind: 'character', team: 'a', position: { row: 5, column: 0 }, name: i ? 'Ally' : 'Self', orderIndex: i,
  snapshot: stats({ characterId: id, isPlayerCharacter: true, basicAttackRange: 0, combatStyle: 'melee' }), gambits: attack, inventory: {},
}));
const input = { version: 2, elementalRulesVersion: 1, seed: 'arena-fixture-party', tickDurationMs: 500, definitions: { statuses },
  actors: shared.placeBattleActors([...chars, mon(wolf, 0, 'char-self', 'principal'), mon(slime, 1, 'char-ally', 'principal'), mon(slime, 2, 'char-self', 'raid')]) };
const party = shared.simulateBattleV2(input);
const sharedView = {
  id: 'shared-1', revision: 1, partyId: 'party-1', mapId: 'map_kwaioua_forest_0', startAt: iso(START), endAt: iso(START + party.durationTicks * 500), state: 'resolved',
  snapshot: { version: 2, tickDurationMs: 500, actors: input.actors.map((a) => ({ id: a.id, name: a.name, kind: a.kind, team: a.team, position: a.position,
    ...(a.kind === 'monster' ? { definitionId: a.definitionId } : {}),
    snapshot: { hp: a.snapshot.hp, sp: a.snapshot.sp, maxHp: a.snapshot.maxHp, maxSp: a.snapshot.maxSp, statusEffects: a.snapshot.statusEffects ?? [] } })) },
  log: { version: 2, outcome: party.outcome, events: party.events, durationTicks: party.durationTicks, actorsAfter: {} },
};

// TypeScript modules (specs can't import JSON); generated — do not edit by hand.
const emit = (file, name, value) => fs.writeFileSync(path.join(here, file), `// Generated by make-fixtures.mjs — do not edit.\n/* eslint-disable */\nexport const ${name}: any = ${JSON.stringify(value)};\n`);
emit('solo-v2.fixture.ts', 'SOLO_V2_ENTRY', soloEntry);
emit('party-v2.fixture.ts', 'PARTY_V2_VIEW', sharedView);
const moves = (events) => events.filter((e) => e.action === 'move').length;
console.log(`solo: ${solo.outcome}, ${solo.durationTicks} ticks, ${solo.log.v2Events.length} events, ${moves(solo.log.v2Events)} moves`);
console.log(`party: ${party.outcome}, ${party.durationTicks} ticks, ${party.events.length} events, ${moves(party.events)} moves, positions ${input.actors.map((a) => `${a.id}@${a.position.row},${a.position.column}`).join(' ')}`);
