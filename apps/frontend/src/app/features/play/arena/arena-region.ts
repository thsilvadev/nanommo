/** Which painted scenery a map gets in the battle arena (by its id prefix: map_<region>_<n>). */
export const ARENA_REGIONS = ['green_grounds', 'menace_hills', 'kwaioua_forest', 'wastelands', 'caete', 'forest_ruins', 'ipora_beach', 'gods_bridge'] as const;
export type ArenaRegionId = typeof ARENA_REGIONS[number];
export const ARENA_ASSET_BASE = '/assets/arena/';

export function arenaRegionOf(mapId: string | null | undefined): ArenaRegionId {
  const key = String(mapId ?? '').replace(/^map_/, '').replace(/_\d+$/, '');
  return (ARENA_REGIONS as readonly string[]).includes(key) ? key as ArenaRegionId : 'green_grounds';
}

/** Parallax layers (sky farthest, near closest) and the tiling ground, generated by tools/arena-assets. */
export function arenaRegionAssets(region: ArenaRegionId): { sky: string; far: string; near: string; ground: string } {
  const dir = `${ARENA_ASSET_BASE}${region}/`;
  return { sky: `${dir}sky.webp`, far: `${dir}far.webp`, near: `${dir}near.webp`, ground: `${dir}ground.webp` };
}
