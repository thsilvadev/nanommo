const assert = require('node:assert/strict');
const path = require('node:path');
const policyPath = path.resolve(__dirname, '../dist/apps/api/src/modules/party/party-policy.js');
assert.ok(require('node:fs').existsSync(policyPath), 'Party lifecycle policy is not implemented');
const { assertPartyJoin, nextPartyLeader, pendingActionAtBoundary, advanceTeleport } = require(policyPath);
assert.doesNotThrow(() => assertPartyJoin({memberIds:['a','b'],candidateId:'c',mapId:'field',candidateMapId:'field',leaderId:'a',requesterId:'a'}));
assert.throws(() => assertPartyJoin({memberIds:['a','b','c','d','e'],candidateId:'f',mapId:'field',candidateMapId:'field',leaderId:'a',requesterId:'a'}), /full/i);
assert.throws(() => assertPartyJoin({memberIds:['a','b'],candidateId:'c',mapId:'field',candidateMapId:'town',leaderId:'a',requesterId:'a'}), /map/i);
assert.throws(() => assertPartyJoin({memberIds:['a','b'],candidateId:'c',mapId:'field',candidateMapId:'field',leaderId:'a',requesterId:'b'}), /leader/i);
assert.equal(pendingActionAtBoundary(4999,5000,false),true);
assert.equal(pendingActionAtBoundary(5000,5000,false),false);
assert.equal(pendingActionAtBoundary(5001,5000,false),false);
assert.equal(pendingActionAtBoundary(4000,5000,true),false);
assert.equal(nextPartyLeader(['b','c'],'seed'),nextPartyLeader(['c','b'],'seed'));
assert.equal(nextPartyLeader([],'seed'),null);
const teleport={elapsedMs:3000,lastAccruedAt:1000,paused:false};
assert.deepEqual(advanceTeleport(teleport,5000,true),{elapsedMs:7000,lastAccruedAt:5000,paused:true});
assert.deepEqual(advanceTeleport({elapsedMs:7000,lastAccruedAt:5000,paused:true},9000,false),{elapsedMs:7000,lastAccruedAt:9000,paused:false});
assert.equal(advanceTeleport({elapsedMs:7000,lastAccruedAt:9000,paused:false},12000,false).elapsedMs,10000);
console.log('party-lifecycle policy passed');
