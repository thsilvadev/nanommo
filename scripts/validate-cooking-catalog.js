const fs = require('fs');
const assert = require('assert');
const read = (path) => JSON.parse(fs.readFileSync(path, 'utf8'));
const recipes = read('cooking_recipes.json').recipes;
assert.deepStrictEqual(recipes, read('apps/frontend/public/data/cooking_recipes.json').recipes, 'Cooking recipe mirror mismatch');
assert.strictEqual(recipes.length, 7, 'Expected seven Cooking recipes');
const items = read('items.json');
const allItems = [...items.consumables, ...items.equipment, ...items.monsterParts, ...items.materials];
recipes.forEach((recipe, index) => {
  assert.strictEqual(recipe.order, index + 1, 'Recipe order must be deterministic and contiguous');
  assert(Number.isInteger(recipe.requiredLevel) && recipe.requiredLevel > 0);
  assert(Number.isInteger(recipe.xpReward) && recipe.xpReward > 0);
  assert(allItems.some(item => item.id === recipe.outputItemId && item.type === 'food' && item.effect?.type === 'food_buff'), 'Invalid recipe output: ' + recipe.outputItemId);
  recipe.ingredients.forEach(ingredient => assert(items.materials.some(item => item.id === ingredient.itemId) && Number.isInteger(ingredient.quantity) && ingredient.quantity > 0, 'Invalid ingredient: ' + ingredient.itemId));
});
const npc = read('npc_catalog.json').npcs.find(row => row.id === 'uncle_phillip');
assert(npc && npc.name === 'Uncle Phillip' && JSON.stringify(npc.types) === '["cooking"]');
assert.strictEqual(npc.greeting, 'Hmmm… delicious… this might go well with tha - Oy! Young traveler! I know you have a great taste for food. You wanna use my kitchen? Fell free to, oy!');
const maps = read('maps.json').maps;
assert(maps.find(map => map.id === 'map_town').npcIds.includes('uncle_phillip'));
assert(maps.filter(map => map.id !== 'map_town').every(map => !(map.npcIds || []).includes('uncle_phillip')));
for (const name of ['items.json', 'npc_catalog.json']) assert.deepStrictEqual(read(name), read('apps/frontend/public/data/' + name), name + ' mirror mismatch');
const thresholds = [0, 100, 220, 390, 640, 1640, 4140, 7890];
const levelForXp = xp => { let level = 1; while (level < thresholds.length && xp >= thresholds[level]) level++; return level; };
assert.strictEqual(levelForXp(20 * 5 + 30 * 18), 5);
assert.strictEqual(levelForXp(20 * 5 + 30 * 18 + 50 * 20), 6);
assert.strictEqual(levelForXp(20 * 5 + 30 * 18 + 50 * 20 + 100 * 25), 7);
assert.strictEqual(allItems.find(item => item.id === 'food_roast').name, 'Roasted Barbecue');
assert(fs.existsSync('apps/frontend/assets/npcs/uncle_phillip.png'));
console.log('Cooking catalogue, mirrors, ingredient/output references, NPC placement, portrait and XP pacing validated.');
